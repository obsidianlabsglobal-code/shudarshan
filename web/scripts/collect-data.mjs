// Collects the REAL eval result files into a generated TS module the app imports.
// Runs before dev/build (locally and on Vercel). A missing file becomes null, so
// the UI can render "—" instead of inventing a number. Never edits the sources.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url)); // web/scripts
const resultsDir = join(here, "..", "..", "eval", "results"); // repo/eval/results

const FILES = {
  authorization: "sudarshan-all.json",
  secret: "secret-all.json",
  gitleaks: "gitleaks-all.json",
  llmReview: "llmreview-classified.json",
  regression: "regression.json",
  stats: "stats.json",
  rewriteBenchmark: "rewrite-benchmark.json",
};

const out = {};
const report = [];
for (const [key, file] of Object.entries(FILES)) {
  const p = join(resultsDir, file);
  if (existsSync(p)) {
    out[key] = JSON.parse(readFileSync(p, "utf8"));
    report.push(`${key}=ok`);
  } else {
    out[key] = null;
    report.push(`${key}=MISSING`);
  }
}

const dataDir = join(here, "..", "src", "data");
mkdirSync(dataDir, { recursive: true });
const banner = "// AUTO-GENERATED by scripts/collect-data.mjs — do not edit. Real eval data only.";
writeFileSync(
  join(dataDir, "results.generated.ts"),
  `${banner}\nexport const results = ${JSON.stringify(out, null, 2)} as const;\n`,
);
console.log("collect-data:", report.join(" "));
