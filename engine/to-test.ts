// Exploit-as-a-test. After a fix is proven, write the exploit out as a
// standalone runnable test into /victim/sudarshan-tests/. The test FAILS on
// vulnerable code and PASSES on fixed code, so it is a permanent regression guard.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

interface Cfg {
  baseUrl: string;
  login: { path: string };
  listOwn: string;
  resourceTemplate: string;
  users: { label: string; username: string; password: string }[];
}
interface StateFile {
  users: { id: string; username: string }[];
  appointments: { id: string; owner_id: string }[];
}

interface TestVars {
  base: string;
  loginPath: string;
  listOwn: string;
  target: string;
  attackerUser: string;
  attackerPass: string;
  path: string;
}

// The generated file uses only string concatenation (no template literals), so
// nothing here needs escaping.
const TEMPLATE = `// AUTO-GENERATED by engine/to-test.ts — BOLA regression test.
// Proven exploit: a non-owner could read GET <TARGET>.
// FAILS on vulnerable code (attacker reads the record), PASSES when fixed.
// Vulnerable build:  npx tsx <PATH>
// Fixed build:       SERVER_FILE=victim/.server.fixed.ts npx tsx <PATH>
import { spawn } from "node:child_process";

const BASE = "<BASE>";
const SERVER_FILE = process.env.SERVER_FILE || "victim/server.ts";
const ATTACKER = { username: "<AU>", password: "<AP>" };
const TARGET = "<TARGET>";
const OWN_LIST = "<OWN>";

function sleep(ms) { return new Promise(function (r) { setTimeout(r, ms); }); }
function stop(p) { try { if (p.pid) process.kill(-p.pid, "SIGKILL"); } catch (e) { try { p.kill("SIGKILL"); } catch (e2) {} } }
async function up() { try { await fetch(BASE + "/"); return true; } catch (e) { return false; } }

async function start() {
  const tsx = process.cwd() + "/node_modules/.bin/tsx";
  const p = spawn(tsx, [SERVER_FILE], { stdio: "ignore", detached: true });
  for (let i = 0; i < 60; i++) { if (await up()) return p; await sleep(200); }
  stop(p);
  throw new Error("server did not start: " + SERVER_FILE);
}

async function main() {
  const srv = await start();
  try {
    const lr = await fetch(BASE + "<LOGIN>", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(ATTACKER) });
    const auth = await lr.json();
    const attack = await fetch(BASE + TARGET, { headers: { authorization: "Bearer " + auth.token } });
    const own = await fetch(BASE + OWN_LIST, { headers: { authorization: "Bearer " + auth.token } });
    const blocked = [401, 403, 404].indexOf(attack.status) !== -1;
    const legitOk = own.status === 200;
    stop(srv);
    if (blocked && legitOk) { console.log("PASS — exploit blocked (status " + attack.status + "), legitimate access intact."); process.exit(0); }
    if (!blocked) { console.error("FAIL — a non-owner read the record (status " + attack.status + "). BOLA present."); process.exit(1); }
    console.error("FAIL — exploit blocked but the legitimate user broke (own-list status " + own.status + ")."); process.exit(1);
  } catch (e) { stop(srv); console.error("ERROR", e); process.exit(2); }
}

main();
`;

function render(v: TestVars): string {
  return TEMPLATE
    .replaceAll("<BASE>", v.base)
    .replaceAll("<LOGIN>", v.loginPath)
    .replaceAll("<OWN>", v.listOwn)
    .replaceAll("<TARGET>", v.target)
    .replaceAll("<AU>", v.attackerUser)
    .replaceAll("<AP>", v.attackerPass)
    .replaceAll("<PATH>", v.path);
}

function main() {
  const cfg = JSON.parse(readFileSync("victim/sudarshan.json", "utf8")) as Cfg;
  const state = JSON.parse(readFileSync("victim/.state.json", "utf8")) as StateFile;

  const victimCfg = cfg.users[0];
  const attackerCfg = cfg.users[1];
  const victimUser = state.users.find((u) => u.username === victimCfg.username);
  if (!victimUser) throw new Error("victim user not found in victim/.state.json (run victim:reset)");
  const appt = state.appointments.find((a) => a.owner_id === victimUser.id);
  if (!appt) throw new Error("no appointment owned by the victim");

  const target = cfg.resourceTemplate.replace("{id}", appt.id);
  const path = `victim/sudarshan-tests/bola-${appt.id}.test.ts`;
  const content = render({
    base: cfg.baseUrl,
    loginPath: cfg.login.path,
    listOwn: cfg.listOwn,
    target,
    attackerUser: attackerCfg.username,
    attackerPass: attackerCfg.password,
    path,
  });

  mkdirSync("victim/sudarshan-tests", { recursive: true });
  writeFileSync(path, content);
  console.log(`wrote ${path}  (exploit: ${attackerCfg.label} reads ${victimCfg.label}'s ${target})`);
}

main();
